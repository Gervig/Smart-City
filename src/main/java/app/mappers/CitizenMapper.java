package app.mappers;

import app.dtos.CitizenDTO;
import app.entities.Citizen;
import app.entities.Family;
import app.entities.Housing;

import java.util.Collection;
import java.util.List;

public final class CitizenMapper {

    private CitizenMapper() {
    }

    public static CitizenDTO toDTO(Citizen citizen) {
        if (citizen == null) return null;
        return CitizenDTO.builder()
                .id(citizen.getId())
                .firstName(citizen.getFirstName())
                .lastName(citizen.getLastName())
                .birthDate(citizen.getBirthDate())
                .deathDate(citizen.getDeathDate())
                .status(citizen.getStatus())
                .gender(citizen.getGender())
                .familyId(citizen.getFamily() != null ? citizen.getFamily().getId() : null)
                .housingId(citizen.getHousing() != null ? citizen.getHousing().getId() : null)
                .build();
    }

    public static List<CitizenDTO> toDTOList(Collection<Citizen> citizens) {
        return citizens.stream().map(CitizenMapper::toDTO).toList();
    }

    /**
     * Builds a new (unsaved) Citizen. The id is not copied - it is generated by the database.
     * The related Family/Housing must be looked up by the caller (e.g. em.find / em.getReference).
     */
    public static Citizen toEntity(CitizenDTO dto, Family family, Housing housing) {
        if (dto == null) return null;
        Citizen citizen = new Citizen();
        updateEntity(citizen, dto);
        citizen.setFamily(family);
        citizen.setHousing(housing);
        return citizen;
    }

    /** Copies the plain fields from the DTO onto an existing Citizen (id and relations untouched). */
    public static void updateEntity(Citizen citizen, CitizenDTO dto) {
        citizen.setFirstName(dto.getFirstName());
        citizen.setLastName(dto.getLastName());
        citizen.setBirthDate(dto.getBirthDate());
        citizen.setDeathDate(dto.getDeathDate());
        citizen.setGender(dto.getGender());
        if (dto.getStatus() != null) citizen.setStatus(dto.getStatus());
    }
}
