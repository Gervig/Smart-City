package app.mappers;

import app.dtos.LocationDTO;
import app.entities.Location;

import java.util.Collection;
import java.util.List;

public final class LocationMapper {

    private LocationMapper() {
    }

    public static LocationDTO toDTO(Location location) {
        if (location == null) return null;
        return LocationDTO.builder()
                .id(location.getId())
                .name(location.getName())
                .streetAddress(location.getStreetAddress())
                .build();
    }

    public static List<LocationDTO> toDTOList(Collection<Location> locations) {
        return locations.stream().map(LocationMapper::toDTO).toList();
    }

    /** Builds a new (unsaved) Location. The id is not copied - it is generated by the database. */
    public static Location toEntity(LocationDTO dto) {
        if (dto == null) return null;
        Location location = new Location();
        updateEntity(location, dto);
        return location;
    }

    /** Copies the plain fields from the DTO onto an existing Location (id untouched). */
    public static void updateEntity(Location location, LocationDTO dto) {
        location.setName(dto.getName());
        location.setStreetAddress(dto.getStreetAddress());
    }
}
