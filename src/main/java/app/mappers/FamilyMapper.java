package app.mappers;

import app.dtos.FamilyDTO;
import app.entities.Family;

import java.util.Collection;
import java.util.List;

public final class FamilyMapper {

    private FamilyMapper() {
    }

    public static FamilyDTO toDTO(Family family) {
        if (family == null) return null;
        return FamilyDTO.builder()
                .id(family.getId())
                .familyName(family.getFamilyName())
                .build();
    }

    public static List<FamilyDTO> toDTOList(Collection<Family> families) {
        return families.stream().map(FamilyMapper::toDTO).toList();
    }

    /** Builds a new (unsaved) Family. The id is not copied - it is generated by the database. */
    public static Family toEntity(FamilyDTO dto) {
        if (dto == null) return null;
        Family family = new Family();
        updateEntity(family, dto);
        return family;
    }

    /** Copies the plain fields from the DTO onto an existing Family (id untouched). */
    public static void updateEntity(Family family, FamilyDTO dto) {
        family.setFamilyName(dto.getFamilyName());
    }
}
